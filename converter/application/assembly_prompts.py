class AssemblyPromptError(ConverterError):
    """Промпт для сборки не выбран, неизвестен или не проходит проверку."""


@dataclass(frozen=True, slots=True)
class AssemblyPrompt:
    """Один вариант предварительного промпта."""

    id: str
    title: str
    text: str


_PROMPTS: tuple[AssemblyPrompt, ...] = (
    AssemblyPrompt(
        id=INVOICE_PROMPT_ID,
        title="Счет на оплату",
        text=INVOICE_PROMPT,
    ),
)
_BY_ID = {prompt.id: prompt for prompt in _PROMPTS}


def list_assembly_prompts() -> tuple[AssemblyPrompt, ...]:
    """Все варианты, доступные клиенту."""
    return _PROMPTS


def resolve_assembly_prompt(prompt_id: str, prompt_text: str | None = None) -> tuple[AssemblyPrompt, str]:
    """Находит вариант и возвращает текст, который уйдёт в тело запроса."""
    key = prompt_id.strip()
    prompt = _BY_ID.get(key)
    if prompt is None:
        raise AssemblyPromptError(f"Неизвестный промпт: {prompt_id.strip() or 'пустой'}")

    text = prompt.text if prompt_text is None else prompt_text
    text = text.strip()
    if not text:
        raise AssemblyPromptError("Укажите предварительный промпт")
    if len(text) > MAX_ASSEMBLY_PROMPT_CHARS:
        raise AssemblyPromptError("Предварительный промпт слишком длинный")
    return prompt, text
